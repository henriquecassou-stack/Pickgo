-- =====================================================================
-- Promoções: desconto em % ou preço fixo para um produto, por período.
-- O preço promocional vale de verdade: o catálogo do totem já devolve o
-- preço com desconto em preco_venda e a cobrança (criar-pagamento) usa
-- a mesma view promocoes_vigentes. Com duas promoções no mesmo produto,
-- vale a de menor preço.
-- =====================================================================

create type tipo_promocao as enum ('percentual', 'preco_fixo');

create table public.promocoes (
  id             bigint generated by default as identity primary key,
  produto_id     uuid not null references public.produtos (id),
  titulo         text check (char_length(titulo) <= 60),   -- ex.: "Semana do chocolate"
  tipo           tipo_promocao not null,
  valor          numeric(10,2) not null check (valor > 0), -- % de desconto ou preço promocional
  inicio         date not null default (now() at time zone 'America/Sao_Paulo')::date,
  fim            date,                                     -- inclusive; null = sem data para acabar
  ativa          boolean not null default true,            -- encerrar = desligar
  criado_em      timestamptz not null default now(),
  atualizado_em  timestamptz not null default now(),
  constraint promocao_percentual check (tipo <> 'percentual' or valor < 100),
  constraint promocao_periodo check (fim is null or fim >= inicio)
);
create index on public.promocoes (produto_id);

alter table public.promocoes enable row level security;
create policy promocoes_admin on public.promocoes for all to authenticated
  using (public.is_admin()) with check (public.is_admin());
grant select, insert, update on public.promocoes to authenticated;
revoke all on public.promocoes from anon;

-- preço final de uma promoção sobre o preço de venda (nunca acima do normal)
create or replace function public.preco_com_promocao(p_preco numeric, p_tipo tipo_promocao, p_valor numeric)
returns numeric language sql immutable as $$
  select greatest(0.01, least(p_preco,
    case when p_tipo = 'percentual' then round(p_preco * (100 - p_valor) / 100, 2) else round(p_valor, 2) end))
$$;

-- promoção que vale hoje (horário de Brasília) para cada produto: a de menor preço
create view public.promocoes_vigentes as
  select distinct on (pr.produto_id)
         pr.produto_id, pr.id as promocao_id, pr.titulo,
         public.preco_com_promocao(p.preco_venda, pr.tipo, pr.valor) as preco_promocional
    from public.promocoes pr
    join public.produtos p on p.id = pr.produto_id
   where pr.ativa
     and pr.inicio <= (now() at time zone 'America/Sao_Paulo')::date
     and (pr.fim is null or pr.fim >= (now() at time zone 'America/Sao_Paulo')::date)
   order by pr.produto_id, preco_promocional, pr.id desc;
revoke all on public.promocoes_vigentes from anon, authenticated;
grant select on public.promocoes_vigentes to service_role;

-- catálogo do totem: preco_venda passa a ser o preço com promoção;
-- preco_original e promocao (título) mostram o "de / por" na tela
create or replace view public.catalogo_totem as
  select p.id, p.nome, p.foto_url, p.codigo_barras,
         coalesce(v.preco_promocional, p.preco_venda)::numeric(10,2) as preco_venda, p.estoque_atual,
         p.categoria_id, c.nome as categoria, c.icone as categoria_icone, c.cor as categoria_cor,
         c.ordem as categoria_ordem,
         p.preco_venda as preco_original,
         case when v.produto_id is null then null else coalesce(v.titulo, 'Promoção') end as promocao
    from public.produtos p
    left join public.categorias c on c.id = p.categoria_id
    left join public.promocoes_vigentes v on v.produto_id = p.id
   where p.ativo and public.is_operador();

-- painel: promoções com o produto e a situação calculada
create view public.promocoes_detalhadas with (security_invoker = true) as
  select pr.*, p.nome as produto_nome, p.preco_venda as preco_normal,
         public.preco_com_promocao(p.preco_venda, pr.tipo, pr.valor) as preco_promocional,
         case
           when not pr.ativa then 'encerrada'
           when pr.fim is not null and pr.fim < (now() at time zone 'America/Sao_Paulo')::date then 'encerrada'
           when pr.inicio > (now() at time zone 'America/Sao_Paulo')::date then 'agendada'
           else 'ativa'
         end as situacao
    from public.promocoes pr
    join public.produtos p on p.id = pr.produto_id;
grant select on public.promocoes_detalhadas to authenticated;
revoke all on public.promocoes_detalhadas from anon;
