create view public.produtos_alertas with (security_invoker = true) as
  select p.*,
         (p.estoque_atual <= p.estoque_minimo) as estoque_baixo,
         (p.validade is not null and p.validade <= (now() at time zone 'America/Sao_Paulo')::date + 7) as perto_validade,
         (p.validade is not null and p.validade < (now() at time zone 'America/Sao_Paulo')::date) as vencido
    from public.produtos p;

create view public.movimentacoes_detalhadas with (security_invoker = true) as
  select m.*,
         p.nome as produto_nome, p.codigo_barras, p.categoria_id,
         c.nome as categoria_nome,
         f.nome as fornecedor_nome,
         u.nome as usuario_nome,
         v.numero as venda_numero
    from public.movimentacoes_estoque m
    join public.produtos p on p.id = m.produto_id
    left join public.categorias c on c.id = p.categoria_id
    left join public.fornecedores f on f.id = m.fornecedor_id
    left join public.usuarios u on u.id = m.usuario_id
    left join public.vendas v on v.id = m.venda_id;

