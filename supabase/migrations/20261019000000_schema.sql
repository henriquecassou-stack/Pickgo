-- Bloqueia alteração "na mão" do saldo. Só o trigger de movimentação
-- (que liga a flag app.movimentando) pode mudar estoque_atual.
create or replace function public.proteger_estoque()
returns trigger language plpgsql as $$
begin
  if tg_op = 'INSERT' then
    new.estoque_atual := 0;  -- estoque inicial entra como movimentação
  elsif new.estoque_atual is distinct from old.estoque_atual
        and coalesce(current_setting('app.movimentando', true), '') <> 'on' then
    raise exception 'estoque_atual só pode ser alterado via movimentacoes_estoque'
      using errcode = 'P0001';
  end if;
  new.atualizado_em := now();
  return new;
end $$;

create trigger trg_produtos_proteger_estoque
  before insert or update on public.produtos
  for each row execute function public.proteger_estoque();

