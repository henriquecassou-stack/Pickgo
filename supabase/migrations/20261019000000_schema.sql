create or replace function public.dashboard_resumo(p_inicio date, p_fim date)
returns json language plpgsql stable security definer set search_path = public as $$
declare
  v_hoje date := (now() at time zone 'America/Sao_Paulo')::date;
  v json;
begin
  perform exigir_admin();
  with pagas as (
    select v.*, (v.pago_em at time zone 'America/Sao_Paulo')::date as dia
      from vendas v where v.status = 'paga'
  )
  select json_build_object(
    'faturamento_hoje',  coalesce((select sum(total) from pagas where dia = v_hoje), 0),
    'faturamento_mes',   coalesce((select sum(total) from pagas where dia >= date_trunc('month', v_hoje)::date and dia <= v_hoje), 0),
    'faturamento',       coalesce((select sum(total) from pagas where dia between p_inicio and p_fim), 0),
    'custo',             coalesce((select sum(custo_total) from pagas where dia between p_inicio and p_fim), 0),
    'lucro_bruto',       coalesce((select sum(total - custo_total) from pagas where dia between p_inicio and p_fim), 0),
    'num_vendas',        (select count(*) from pagas where dia between p_inicio and p_fim),
    'ticket_medio',      coalesce((select avg(total) from pagas where dia between p_inicio and p_fim), 0),
    'itens_vendidos',    coalesce((select sum(i.quantidade) from itens_venda i join pagas p on p.id = i.venda_id where p.dia between p_inicio and p_fim), 0)
  ) into v;
  return v;
end $$;

create or replace function public.dashboard_serie(p_inicio date, p_fim date, p_agrupamento text default 'dia')
returns table (periodo date, faturamento numeric, lucro numeric, vendas bigint)
language plpgsql stable security definer set search_path = public as $$
#variable_conflict use_column
declare
  v_passo interval := case p_agrupamento when 'semana' then interval '1 week' when 'mes' then interval '1 month' else interval '1 day' end;
  v_trunc text     := case p_agrupamento when 'semana' then 'week' when 'mes' then 'month' else 'day' end;
begin
  perform exigir_admin();
  return query
  with eixo as (
    select generate_series(date_trunc(v_trunc, p_inicio::timestamp), date_trunc(v_trunc, p_fim::timestamp), v_passo)::date as periodo
  ), agg as (
    select date_trunc(v_trunc, (v.pago_em at time zone 'America/Sao_Paulo'))::date as periodo,
           sum(v.total) as faturamento, sum(v.total - v.custo_total) as lucro, count(*) as vendas
      from vendas v
     where v.status = 'paga'
       and (v.pago_em at time zone 'America/Sao_Paulo')::date between p_inicio and p_fim
     group by 1
  )
  select e.periodo, coalesce(a.faturamento, 0), coalesce(a.lucro, 0), coalesce(a.vendas, 0)
    from eixo e left join agg a using (periodo)
   order by e.periodo;
end $$;

create or replace function public.dashboard_top_produtos(p_inicio date, p_fim date, p_limite int default 10)
returns table (produto_id uuid, nome text, quantidade bigint, faturamento numeric, lucro numeric)
language plpgsql stable security definer set search_path = public as $$
#variable_conflict use_column
begin
  perform exigir_admin();
  return query
  select i.produto_id, max(i.nome_produto), sum(i.quantidade)::bigint, sum(i.subtotal),
         sum(i.subtotal - i.quantidade * i.custo_unitario)
    from itens_venda i join vendas v on v.id = i.venda_id
   where v.status = 'paga'
     and (v.pago_em at time zone 'America/Sao_Paulo')::date between p_inicio and p_fim
   group by i.produto_id
   order by 3 desc, 4 desc
   limit p_limite;
end $$;

create or replace function public.dashboard_categorias(p_inicio date, p_fim date)
returns table (categoria text, cor text, quantidade bigint, faturamento numeric, lucro numeric)
language plpgsql stable security definer set search_path = public as $$
#variable_conflict use_column
begin
  perform exigir_admin();
  return query
  select coalesce(c.nome, 'Sem categoria'), coalesce(c.cor, '#94a3b8'), sum(i.quantidade)::bigint, sum(i.subtotal),
         sum(i.subtotal - i.quantidade * i.custo_unitario)
    from itens_venda i
    join vendas v on v.id = i.venda_id
    join produtos p on p.id = i.produto_id
    left join categorias c on c.id = p.categoria_id
   where v.status = 'paga'
     and (v.pago_em at time zone 'America/Sao_Paulo')::date between p_inicio and p_fim
   group by c.nome, c.cor
   order by 4 desc;
end $$;

create or replace function public.dashboard_metodos(p_inicio date, p_fim date)
returns table (metodo metodo_pagamento, vendas bigint, faturamento numeric)
language plpgsql stable security definer set search_path = public as $$
#variable_conflict use_column
begin
  perform exigir_admin();
  return query
  select v.metodo, count(*)::bigint, sum(v.total)
    from vendas v
   where v.status = 'paga'
     and (v.pago_em at time zone 'America/Sao_Paulo')::date between p_inicio and p_fim
   group by v.metodo
   order by 3 desc;
end $$;

