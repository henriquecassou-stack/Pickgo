create type perfil_usuario     as enum ('admin', 'totem');
create type tipo_movimentacao  as enum ('entrada', 'saida');
create type motivo_movimentacao as enum (
  'reposicao',        -- entrada: compra/reposição
  'ajuste_entrada',   -- entrada: correção de inventário
  'venda',            -- saída automática por venda paga
  'vencido',
  'avariado',
  'perda',
  'consumo_interno',
  'ajuste_saida'      -- saída: correção de inventário
);
create type status_venda      as enum ('aguardando_pagamento', 'paga', 'recusada', 'expirada', 'cancelada');
create type status_pagamento  as enum ('pendente', 'aprovado', 'recusado', 'expirado', 'cancelado');
create type metodo_pagamento  as enum ('pix', 'cartao_credito', 'cartao_debito');

