-- Catálogo do totem: só colunas seguras (sem custo) e produtos ativos.
-- A view roda com o dono (ignora RLS de produtos) e checa o perfil.
-- ---------------------------------------------------------------------
create view public.catalogo_totem as
  select p.id, p.nome, p.foto_url, p.codigo_barras, p.preco_venda, p.estoque_atual,
         p.categoria_id, c.nome as categoria, c.icone as categoria_icone, c.cor as categoria_cor,
         c.ordem as categoria_ordem
    from public.produtos p
    left join public.categorias c on c.id = p.categoria_id
   where p.ativo and public.is_operador();

