-- Aprova o pagamento, marca a venda como paga e baixa o estoque.
-- Idempotente: webhooks repetidos não baixam o estoque duas vezes.
create or replace function public.finalizar_pagamento(
  p_pagamento_id uuid,
  p_id_externo   text default null,
  p_resposta     jsonb default null
) returns boolean language plpgsql security definer set search_path = public as $$
declare
  v_pag  pagamentos%rowtype;
  v_item record;
begin
  select * into v_pag from pagamentos where id = p_pagamento_id for update;
  if not found then
    raise exception 'Pagamento % não encontrado', p_pagamento_id;
  end if;
  if v_pag.status = 'aprovado' then
    return false;  -- já processado
  end if;

  -- Mesmo que o totem já tenha expirado o QR, se o provedor confirmou o
  -- dinheiro entrou: a venda é concluída.
  update pagamentos
     set status = 'aprovado',
         aprovado_em = now(),
         atualizado_em = now(),
         id_externo = coalesce(p_id_externo, id_externo),
         resposta_provedor = coalesce(p_resposta, resposta_provedor),
         motivo_recusa = null
   where id = p_pagamento_id;

  update vendas set status = 'paga', pago_em = now() where id = v_pag.venda_id;

  for v_item in
    select produto_id, sum(quantidade)::int as qtd, max(custo_unitario) as custo
      from itens_venda where venda_id = v_pag.venda_id
     group by produto_id
  loop
    insert into movimentacoes_estoque (produto_id, tipo, motivo, quantidade, custo_unitario, venda_id, usuario_id, observacao)
    values (v_item.produto_id, 'saida', 'venda', v_item.qtd, v_item.custo, v_pag.venda_id, v_pag.totem_id,
            'Venda #' || (select numero from vendas where id = v_pag.venda_id));
  end loop;

  return true;
end $$;

-- Marca pagamento como recusado / expirado / cancelado (sem mexer no estoque).
create or replace function public.encerrar_pagamento(
  p_pagamento_id uuid,
  p_status       status_pagamento,
  p_motivo       text default null,
  p_resposta     jsonb default null
) returns boolean language plpgsql security definer set search_path = public as $$
declare
  v_pag pagamentos%rowtype;
begin
  if p_status not in ('recusado', 'expirado', 'cancelado') then
    raise exception 'Status inválido para encerrar: %', p_status;
  end if;
  select * into v_pag from pagamentos where id = p_pagamento_id for update;
  if not found or v_pag.status <> 'pendente' then
    return false;
  end if;
  update pagamentos
     set status = p_status, motivo_recusa = p_motivo, atualizado_em = now(),
         resposta_provedor = coalesce(p_resposta, resposta_provedor)
   where id = p_pagamento_id;
  update vendas
     set status = case p_status when 'recusado' then 'recusada'::status_venda
                                when 'expirado' then 'expirada'::status_venda
                                else 'cancelada'::status_venda end
   where id = v_pag.venda_id and status = 'aguardando_pagamento';
  return true;
end $$;

-- Expira pagamentos pendentes vencidos (chamado ao criar novos pagamentos
-- e opcionalmente via pg_cron).
create or replace function public.expirar_pagamentos_vencidos()
returns integer language plpgsql security definer set search_path = public as $$
declare
  v_id uuid;
  v_n  integer := 0;
begin
  for v_id in select id from pagamentos where status = 'pendente' and expira_em < now() - interval '1 minute' loop
    if public.encerrar_pagamento(v_id, 'expirado', 'QR Code expirado') then v_n := v_n + 1; end if;
  end loop;
  return v_n;
end $$;

revoke all on function public.finalizar_pagamento(uuid, text, jsonb) from public, anon, authenticated;
revoke all on function public.encerrar_pagamento(uuid, status_pagamento, text, jsonb) from public, anon, authenticated;
revoke all on function public.expirar_pagamentos_vencidos() from public, anon, authenticated;

