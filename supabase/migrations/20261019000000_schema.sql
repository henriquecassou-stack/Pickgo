-- =====================================================================
-- Mercado Autônomo — esquema do banco (Supabase / PostgreSQL)
--
-- Regras centrais:
--   * produtos.estoque_atual NUNCA é alterado diretamente. Só muda quando
--     uma linha é inserida em movimentacoes_estoque (trigger abaixo).
--   * Movimentações são imutáveis (sem UPDATE/DELETE). Correção = nova
--     movimentação de ajuste.
--   * A venda só vira "paga" e o estoque só é baixado por
--     finalizar_pagamento(), chamada pelo backend após confirmação do
--     provedor (webhook) — nunca pelo navegador.
-- =====================================================================


