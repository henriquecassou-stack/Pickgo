-- ---------------------------------------------------------------------
-- Movimentações de estoque (fonte da verdade do saldo)
-- ---------------------------------------------------------------------
create table public.movimentacoes_estoque (
  id                 bigint generated by default as identity primary key,
  produto_id         uuid not null references public.produtos (id),
  tipo               tipo_movimentacao not null,
  motivo             motivo_movimentacao not null,
  quantidade         integer not null check (quantidade > 0),
  custo_unitario     numeric(10,2) check (custo_unitario >= 0),
  fornecedor_id      bigint references public.fornecedores (id),
  venda_id           uuid references public.vendas (id),
  observacao         text,
  data_movimentacao  timestamptz not null default now(),
  usuario_id         uuid references public.usuarios (id) default auth.uid(),
  saldo_anterior     integer not null default 0,
  saldo_posterior    integer not null default 0,
  criado_em          timestamptz not null default now(),
  constraint motivo_coerente check (
    (tipo = 'entrada' and motivo in ('reposicao', 'ajuste_entrada')) or
    (tipo = 'saida'   and motivo not in ('reposicao', 'ajuste_entrada'))
  ),
  constraint venda_so_em_saida_por_venda check ((motivo = 'venda') = (venda_id is not null))
);
create index on public.movimentacoes_estoque (produto_id, data_movimentacao desc);
create index on public.movimentacoes_estoque (data_movimentacao desc);
create index on public.movimentacoes_estoque (venda_id);

create or replace function public.aplicar_movimentacao()
returns trigger language plpgsql security definer set search_path = public as $$
declare
  v_saldo integer;
begin
  -- trava a linha do produto: movimentações simultâneas ficam em fila
  select estoque_atual into v_saldo from produtos where id = new.produto_id for update;
  if not found then
    raise exception 'Produto % não encontrado', new.produto_id;
  end if;

  new.saldo_anterior  := v_saldo;
  new.saldo_posterior := v_saldo + case when new.tipo = 'entrada' then new.quantidade else -new.quantidade end;

  -- Saída manual não pode deixar saldo negativo. A saída por venda pode
  -- (o morador já levou o produto; o negativo sinaliza erro de inventário).
  if new.saldo_posterior < 0 and new.motivo <> 'venda' then
    raise exception 'Estoque insuficiente: saldo atual %, saída de %', v_saldo, new.quantidade
      using errcode = 'P0001';
  end if;

  perform set_config('app.movimentando', 'on', true);
  update produtos
     set estoque_atual = new.saldo_posterior,
         -- reposição atualiza o custo para o último custo de compra
         preco_custo = case when new.motivo = 'reposicao' and new.custo_unitario is not null
                            then new.custo_unitario else preco_custo end
   where id = new.produto_id;
  perform set_config('app.movimentando', 'off', true);

  return new;
end $$;

create trigger trg_movimentacao_aplicar
  before insert on public.movimentacoes_estoque
  for each row execute function public.aplicar_movimentacao();

