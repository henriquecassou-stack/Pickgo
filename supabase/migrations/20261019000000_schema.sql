create policy fornecedores_admin on public.fornecedores for all to authenticated using (public.is_admin()) with check (public.is_admin());

-- produtos: só admin (o totem usa a view catalogo_totem). Sem DELETE:
-- produto é desativado para preservar o histórico.
create policy produtos_ler     on public.produtos for select to authenticated using (public.is_admin());
create policy produtos_inserir on public.produtos for insert to authenticated with check (public.is_admin());
create policy produtos_editar  on public.produtos for update to authenticated using (public.is_admin()) with check (public.is_admin());

-- movimentações: admin lê e registra entradas/saídas manuais.
-- Saídas por venda só via finalizar_pagamento().
create policy mov_ler on public.movimentacoes_estoque for select to authenticated using (public.is_admin());
create policy mov_inserir on public.movimentacoes_estoque for insert to authenticated
  with check (public.is_admin() and motivo <> 'venda' and usuario_id = auth.uid());

-- vendas / itens / pagamentos: admin lê tudo; totem lê só as próprias
-- (necessário para o realtime do status do pagamento). Escrita só backend.
create policy vendas_ler on public.vendas for select to authenticated
  using (public.is_admin() or totem_id = auth.uid());
create policy itens_ler on public.itens_venda for select to authenticated
  using (public.is_admin() or exists (select 1 from public.vendas v where v.id = venda_id and v.totem_id = auth.uid()));
create policy pagamentos_ler on public.pagamentos for select to authenticated
  using (public.is_admin() or totem_id = auth.uid());

grant select on public.catalogo_totem, public.produtos_alertas, public.movimentacoes_detalhadas to authenticated;
revoke all on public.catalogo_totem, public.produtos_alertas, public.movimentacoes_detalhadas from anon;

-- ---------------------------------------------------------------------
-- Realtime: totem acompanha o status do pagamento; painel vê novas vendas
-- ---------------------------------------------------------------------
do $$
begin
  if exists (select 1 from pg_publication where pubname = 'supabase_realtime') then
    alter publication supabase_realtime add table public.pagamentos, public.vendas, public.produtos;
  end if;
end $$;

-- ---------------------------------------------------------------------
-- Storage: fotos dos produtos (leitura pública, escrita só admin)
-- ---------------------------------------------------------------------
insert into storage.buckets (id, name, public)
values ('produtos', 'produtos', true)
on conflict (id) do nothing;

create policy fotos_produtos_ler on storage.objects for select
  using (bucket_id = 'produtos');
create policy fotos_produtos_admin_inserir on storage.objects for insert to authenticated
  with check (bucket_id = 'produtos' and public.is_admin());
create policy fotos_produtos_admin_editar on storage.objects for update to authenticated
  using (bucket_id = 'produtos' and public.is_admin());
create policy fotos_produtos_admin_apagar on storage.objects for delete to authenticated
  using (bucket_id = 'produtos' and public.is_admin());
