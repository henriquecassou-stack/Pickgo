create table public.usuarios (
  id         uuid primary key references auth.users (id) on delete cascade,
  nome       text not null default '',
  email      text,
  perfil     perfil_usuario not null default 'totem',
  ativo      boolean not null default true,
  criado_em  timestamptz not null default now()
);

-- Cria o perfil automaticamente ao criar o usuário no Auth.
-- O perfil vem de app_metadata (só o service role consegue definir);
-- sem isso o usuário nasce como 'totem' (menor privilégio de admin).
create or replace function public.criar_perfil_usuario()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  insert into public.usuarios (id, nome, email, perfil)
  values (
    new.id,
    coalesce(new.raw_user_meta_data ->> 'nome', split_part(new.email, '@', 1)),
    new.email,
    coalesce((new.raw_app_meta_data ->> 'perfil')::perfil_usuario, 'totem')
  )
  on conflict (id) do nothing;
  return new;
end $$;

create trigger trg_auth_novo_usuario
  after insert on auth.users
  for each row execute function public.criar_perfil_usuario();

create or replace function public.perfil_atual()
returns perfil_usuario language sql stable security definer set search_path = public as $$
  select perfil from public.usuarios where id = auth.uid() and ativo
$$;

create or replace function public.is_admin()
returns boolean language sql stable security definer set search_path = public as $$
  select coalesce(public.perfil_atual() = 'admin', false)
$$;

create or replace function public.is_operador()  -- admin ou totem
returns boolean language sql stable security definer set search_path = public as $$
  select public.perfil_atual() is not null
$$;

