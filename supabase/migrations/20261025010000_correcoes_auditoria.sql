-- BUG-004: identificador da tentativa (gerado no totem antes de pedir a cobrança).
-- Reenviar a mesma tentativa devolve a mesma venda/cobrança.
alter table public.pagamentos add column tentativa_id uuid unique;

-- BUG-007: venda offline com preço diferente do catálogo fica marcada
alter table public.vendas add column preco_divergente boolean not null default false;

-- BUG-002/006: vendas offline que o servidor recusou (ou fila corrompida no totem)
-- ficam guardadas para o administrador conferir, em vez de sumirem.
create table public.vendas_offline_rejeitadas (
  id         bigint generated by default as identity primary key,
  txid       text unique,
  payload    jsonb not null,
  erro       text not null,
  totem_id   uuid references public.usuarios (id),
  resolvida  boolean not null default false,
  criado_em  timestamptz not null default now()
);
alter table public.vendas_offline_rejeitadas enable row level security;
create policy rejeitadas_admin_ler on public.vendas_offline_rejeitadas for select to authenticated using (public.is_admin());
create policy rejeitadas_admin_editar on public.vendas_offline_rejeitadas for update to authenticated using (public.is_admin()) with check (public.is_admin());
grant select, update on public.vendas_offline_rejeitadas to authenticated;
revoke all on public.vendas_offline_rejeitadas from anon;

-- preço que um produto podia ter numa data: o normal ou o de alguma promoção daquele dia
create or replace function public.preco_aceito(p_produto uuid, p_preco numeric, p_dia date)
returns boolean language sql stable security definer set search_path = public as $$
  select exists (
    select 1 from produtos p where p.id = p_produto and abs(p.preco_venda - p_preco) < 0.005
    union all
    select 1 from promocoes pr join produtos p on p.id = pr.produto_id
     where pr.produto_id = p_produto
       and pr.inicio <= p_dia and (pr.fim is null or pr.fim >= p_dia)
       and abs(preco_com_promocao(p.preco_venda, pr.tipo, pr.valor) - p_preco) < 0.005
  )
$$;

create or replace function public.registrar_venda_offline(p jsonb)
returns json language plpgsql security definer set search_path = public as $$
declare
  v_existente vendas%rowtype;
  v_venda     uuid;
  v_numero    bigint;
  v_pag       uuid;
  v_total     numeric := 0;
  v_custo     numeric := 0;
  v_item      jsonb;
  v_prod      produtos%rowtype;
  v_qtd       int;
  v_preco     numeric;
  v_quando    timestamptz := coalesce((p ->> 'criado_em')::timestamptz, now());
  v_dia       date;
  v_tipo      tipo_cliente := coalesce((p ->> 'tipo_cliente')::tipo_cliente, 'morador');
  v_apto      text := case when v_tipo = 'visitante' then null else nullif(left(trim(p ->> 'apartamento'), 20), '') end;
  v_cpf       text := so_digitos(p ->> 'cpf');
  v_morador   moradores%rowtype;
  v_diverg    text := '';
begin
  if not is_operador() then
    raise exception 'Não autorizado' using errcode = '42501';
  end if;
  if coalesce(p ->> 'txid', '') !~ '^[A-Za-z0-9]{6,25}$' then
    raise exception 'txid inválido';
  end if;
  -- data no futuro não vale (relógio do totem errado): usa o horário do servidor
  if v_quando > now() + interval '5 minutes' then v_quando := now(); end if;
  v_dia := (v_quando at time zone 'America/Sao_Paulo')::date;

  select * into v_existente from vendas where txid = p ->> 'txid';
  if found then
    return json_build_object('numero', v_existente.numero, 'repetida', true);
  end if;
  if jsonb_array_length(coalesce(p -> 'itens', '[]')) = 0 then
    raise exception 'Venda offline sem itens';
  end if;

  if v_tipo = 'morador_cadastrado' then
    -- BUG-002: morador identificado por apartamento + PIN antes da queda: usa o cadastro
    select * into v_morador from moradores where id = nullif(p ->> 'morador_id', '')::uuid and ativo;
    if not found then raise exception 'Cadastro do morador não encontrado'; end if;
    v_apto := case when v_morador.bloco is not null then v_morador.apartamento || ' ' || v_morador.bloco else v_morador.apartamento end;
    v_cpf := null;
  else
    if v_cpf is not null and not cpf_valido(v_cpf) then v_cpf := null; end if;
    -- visitante e morador sem cadastro informam o CPF
    if v_cpf is null then raise exception 'CPF do cliente inválido'; end if;
  end if;

  for v_item in select * from jsonb_array_elements(p -> 'itens') loop
    select * into v_prod from produtos where id = (v_item ->> 'produto_id')::uuid;
    if not found then raise exception 'Produto % não encontrado', v_item ->> 'produto_id'; end if;
    v_qtd := (v_item ->> 'quantidade')::int;
    v_preco := round((v_item ->> 'preco_unitario')::numeric, 2);
    if v_qtd is null or v_qtd < 1 or v_qtd > 50 or v_preco is null or v_preco <= 0 then raise exception 'Item inválido'; end if;
    -- BUG-007: o preço precisa ser o do catálogo (normal ou promoção daquele dia)
    if not preco_aceito(v_prod.id, v_preco, v_dia) then
      v_diverg := v_diverg || v_prod.nome || ': cobrado R$ ' || replace(trim(to_char(v_preco, '99999990.00')), '.', ',')
        || ', catálogo R$ ' || replace(trim(to_char(v_prod.preco_venda, '99999990.00')), '.', ',') || '. ';
    end if;
    v_total := v_total + v_qtd * v_preco;
    v_custo := v_custo + v_qtd * v_prod.preco_custo;
  end loop;

  insert into vendas (metodo, apartamento, tipo_cliente, morador_id, cpf_cliente, total, custo_total, totem_id, criado_em, offline, txid, conferencia, preco_divergente)
  values ('pix', v_apto, v_tipo, v_morador.id, v_cpf, v_total, v_custo, auth.uid(), v_quando, true, p ->> 'txid', 'pendente', v_diverg <> '')
  returning id, numero into v_venda, v_numero;

  insert into itens_venda (venda_id, produto_id, nome_produto, quantidade, preco_unitario, custo_unitario)
  select v_venda, pr.id, pr.nome, (i ->> 'quantidade')::int, round((i ->> 'preco_unitario')::numeric, 2), pr.preco_custo
    from jsonb_array_elements(p -> 'itens') i join produtos pr on pr.id = (i ->> 'produto_id')::uuid;

  insert into pagamentos (venda_id, totem_id, provedor, metodo, valor, id_externo, expira_em, criado_em)
  values (v_venda, auth.uid(), 'pix_offline', 'pix', v_total, p ->> 'txid', v_quando + interval '1 day', v_quando)
  returning id into v_pag;

  perform finalizar_pagamento(v_pag, p ->> 'txid', jsonb_build_object('offline', true));
  update vendas set pago_em = v_quando where id = v_venda;

  if avisos_ligados() then
    perform abrir_aviso('venda_offline', 'atencao', 'PIX sem internet a conferir: compra #' || v_numero,
      'Compra de R$ ' || replace(trim(to_char(v_total, '99999990.00')), '.', ',') || ' paga por PIX enquanto o totem estava sem internet ('
      || to_char(v_quando at time zone 'America/Sao_Paulo', 'DD/MM HH24:MI') || '). Confira no extrato o identificador '
      || (p ->> 'txid') || '.', '/admin/pix', v_venda::text, false);
    if v_diverg <> '' then
      perform abrir_aviso('preco_divergente', 'critico', 'Preço diferente do catálogo: compra #' || v_numero,
        'A compra sem internet chegou com preço que não bate com o catálogo nem com promoções do dia. ' || v_diverg
        || 'Confira antes de marcar como recebida.', '/admin/pix', v_venda::text, false);
    end if;
  end if;

  return json_build_object('numero', v_numero, 'repetida', false, 'preco_divergente', v_diverg <> '');
end $$;

-- BUG-002/006: o totem registra uma venda offline que o servidor recusou, ou uma fila
-- corrompida, para não perder a compra; abre aviso urgente para o administrador.
create or replace function public.registrar_rejeicao_offline(p jsonb, p_erro text)
returns void language plpgsql security definer set search_path = public as $$
declare
  v_txid text := nullif(left(p ->> 'txid', 40), '');
  v_id   bigint;
begin
  if not is_operador() then
    raise exception 'Não autorizado' using errcode = '42501';
  end if;
  insert into vendas_offline_rejeitadas (txid, payload, erro, totem_id)
  values (v_txid, p, left(coalesce(p_erro, 'erro desconhecido'), 300), auth.uid())
  on conflict (txid) do nothing
  returning id into v_id;
  if v_id is not null and avisos_ligados() then
    perform abrir_aviso('venda_offline_rejeitada', 'critico', 'Compra sem internet não registrada',
      'Uma compra feita sem internet não pôde ser registrada (' || left(coalesce(p_erro, ''), 120) || '). '
      || coalesce('Valor informado: R$ ' || replace(trim(to_char((p ->> 'total')::numeric, '99999990.00')), '.', ',') || '. ', '')
      || coalesce('Identificador PIX: ' || v_txid || '. ', '')
      || 'Os dados ficaram guardados; confira o extrato e registre a venda manualmente se o pagamento entrou.',
      '/admin/pix', 'rejeitada-' || v_id, false);
  end if;
end $$;

-- BUG-008: estorno (refunded) ou contestação (charged_back) de um pagamento aprovado.
-- A venda sai do faturamento (status 'estornada'); o estoque não volta, porque o produto
-- saiu da loja. Idempotente. Só o backend (service role) chama.
create or replace function public.registrar_estorno(p_pagamento_id uuid, p_status status_pagamento, p_resposta jsonb default null)
returns boolean language plpgsql security definer set search_path = public as $$
declare
  v_pag pagamentos%rowtype;
  v_num bigint;
begin
  if p_status not in ('estornado', 'contestado') then
    raise exception 'Status de estorno inválido: %', p_status;
  end if;
  select * into v_pag from pagamentos where id = p_pagamento_id for update;
  if not found then raise exception 'Pagamento % não encontrado', p_pagamento_id; end if;
  if v_pag.status = p_status then return false; end if;            -- já registrado
  if v_pag.status not in ('aprovado', 'estornado', 'contestado') then return false; end if;

  update pagamentos set status = p_status, atualizado_em = now(),
         resposta_provedor = coalesce(p_resposta, resposta_provedor),
         motivo_recusa = case p_status when 'estornado' then 'Pagamento estornado' else 'Pagamento contestado (chargeback)' end
   where id = p_pagamento_id;
  update vendas set status = 'estornada' where id = v_pag.venda_id returning numero into v_num;

  perform abrir_aviso('estorno', 'critico',
    case p_status when 'estornado' then 'Estorno na compra #' else 'Contestação (chargeback) na compra #' end || v_num,
    'O pagamento de R$ ' || replace(trim(to_char(v_pag.valor, '99999990.00')), '.', ',')
    || case p_status when 'estornado' then ' foi devolvido ao cliente' else ' foi contestado pelo cliente no banco' end
    || '. A compra saiu do faturamento; o estoque continua baixado.', '/admin/vendas', v_pag.venda_id::text, true);
  return true;
end $$;

-- permissões (a migração de permissões tirou o acesso padrão)
revoke execute on function public.preco_aceito(uuid, numeric, date) from public, anon, authenticated;
revoke execute on function public.registrar_estorno(uuid, status_pagamento, jsonb) from public, anon, authenticated;
revoke execute on function public.registrar_rejeicao_offline(jsonb, text) from public, anon;
grant execute on function public.registrar_rejeicao_offline(jsonb, text) to authenticated;
grant execute on function public.registrar_venda_offline(jsonb) to authenticated;
grant execute on all functions in schema public to service_role;
