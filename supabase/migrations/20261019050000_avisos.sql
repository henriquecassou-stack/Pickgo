-- =====================================================================
-- Avisos para o administrador (estoque, validade e avaliações)
--
-- Gerados pelo próprio banco:
--   * estoque baixo/zerado  -> trigger a cada mudança de estoque
--   * validade próxima/vencido -> verificar_avisos() (pg_cron diário e
--     também ao abrir o painel)
--   * avaliação ruim (nota <= 2) e sugestão de produto -> trigger
-- Um aviso de estoque/validade fica "aberto" até a situação se resolver
-- (ex.: reposição); não se repete enquanto estiver aberto.
-- O envio por e-mail/WhatsApp é feito pela Edge Function enviar-avisos.
-- =====================================================================

create type tipo_aviso as enum (
  'estoque_baixo', 'estoque_zerado', 'validade_proxima', 'produto_vencido', 'avaliacao_baixa', 'sugestao_produto'
);
create type gravidade_aviso as enum ('info', 'atencao', 'critico');

create table public.avisos (
  id             bigint generated by default as identity primary key,
  tipo           tipo_aviso not null,
  gravidade      gravidade_aviso not null,
  titulo         text not null,
  mensagem       text not null,
  link           text,
  referencia_id  text not null,           -- produto ou avaliação
  lido           boolean not null default false,
  resolvido      boolean not null default false,
  resolvido_em   timestamptz,
  enviado_em     timestamptz,             -- quando foi para e-mail/WhatsApp
  criado_em      timestamptz not null default now()
);
create unique index avisos_um_aberto on public.avisos (tipo, referencia_id) where not resolvido;
create index on public.avisos (criado_em desc);
create index on public.avisos (lido) where not lido;

-- Configuração de envio (linha única)
create table public.config_avisos (
  id               smallint primary key default 1 check (id = 1),
  email            text,
  whatsapp         text,
  enviar_imediato  boolean not null default true,     -- manda críticos/atenção assim que surgem
  niveis_imediato  gravidade_aviso[] not null default '{critico,atencao}',
  resumo_diario    boolean not null default true,     -- resumo do dia anterior às 8h
  atualizado_em    timestamptz not null default now()
);
insert into public.config_avisos (id) values (1);

-- permite desligar os avisos durante cargas em massa (seed)
create or replace function public.avisos_ligados()
returns boolean language sql stable as $$
  select coalesce(current_setting('app.sem_avisos', true), '') <> 'on'
$$;

create or replace function public.abrir_aviso(
  p_tipo tipo_aviso, p_gravidade gravidade_aviso, p_titulo text, p_mensagem text, p_link text, p_ref text, p_atualizar boolean default false
) returns void language plpgsql security definer set search_path = public as $$
begin
  if p_atualizar then
    insert into avisos (tipo, gravidade, titulo, mensagem, link, referencia_id)
    values (p_tipo, p_gravidade, p_titulo, p_mensagem, p_link, p_ref)
    on conflict (tipo, referencia_id) where not resolvido
    do update set mensagem = excluded.mensagem, titulo = excluded.titulo;
  else
    insert into avisos (tipo, gravidade, titulo, mensagem, link, referencia_id)
    values (p_tipo, p_gravidade, p_titulo, p_mensagem, p_link, p_ref)
    on conflict (tipo, referencia_id) where not resolvido do nothing;
  end if;
end $$;

create or replace function public.resolver_avisos(p_ref text, p_tipos tipo_aviso[])
returns void language sql security definer set search_path = public as $$
  update avisos set resolvido = true, resolvido_em = now()
   where referencia_id = p_ref and tipo = any(p_tipos) and not resolvido
$$;

-- ---------------------------------------------------------------------
-- Estoque: avalia o produto e abre/resolve os avisos
-- ---------------------------------------------------------------------
create or replace function public.avaliar_estoque_produto(p produtos)
returns void language plpgsql security definer set search_path = public as $$
declare
  v_link text := '/admin/produtos/' || p.id;
begin
  if not p.ativo or p.estoque_atual > p.estoque_minimo then
    perform resolver_avisos(p.id::text, '{estoque_baixo,estoque_zerado}');
  elsif p.estoque_atual <= 0 then
    perform resolver_avisos(p.id::text, '{estoque_baixo}');
    perform abrir_aviso('estoque_zerado', 'critico', 'Estoque zerado: ' || p.nome,
      p.nome || ' está sem estoque (' || p.estoque_atual || ' un.). Reponha o quanto antes.', v_link, p.id::text, true);
  else
    perform resolver_avisos(p.id::text, '{estoque_zerado}');
    perform abrir_aviso('estoque_baixo', 'atencao', 'Estoque baixo: ' || p.nome,
      p.nome || ' está com ' || p.estoque_atual || ' un. (mínimo ' || p.estoque_minimo || ').', v_link, p.id::text, true);
  end if;
end $$;

create or replace function public.avaliar_validade_produto(p produtos)
returns void language plpgsql security definer set search_path = public as $$
declare
  v_hoje date := (now() at time zone 'America/Sao_Paulo')::date;
  v_link text := '/admin/produtos/' || p.id;
  v_dias int;
begin
  if not p.ativo or p.validade is null or p.validade > v_hoje + 7 then
    perform resolver_avisos(p.id::text, '{validade_proxima,produto_vencido}');
  elsif p.validade < v_hoje then
    perform resolver_avisos(p.id::text, '{validade_proxima}');
    if p.estoque_atual > 0 then
      perform abrir_aviso('produto_vencido', 'critico', 'Produto vencido: ' || p.nome,
        p.nome || ' venceu em ' || to_char(p.validade, 'DD/MM/YYYY') || ' e ainda há ' || p.estoque_atual
        || ' un. no estoque. Retire da prateleira e registre a saída.', v_link, p.id::text, true);
    else
      perform resolver_avisos(p.id::text, '{produto_vencido}');
    end if;
  else
    v_dias := p.validade - v_hoje;
    perform resolver_avisos(p.id::text, '{produto_vencido}');
    if p.estoque_atual > 0 then
      perform abrir_aviso('validade_proxima', 'atencao', 'Validade próxima: ' || p.nome,
        p.nome || case v_dias when 0 then ' vence hoje' when 1 then ' vence amanhã' else ' vence em ' || v_dias || ' dias' end
        || ' (' || to_char(p.validade, 'DD/MM/YYYY') || '), com ' || p.estoque_atual || ' un. em estoque.', v_link, p.id::text, true);
    else
      perform resolver_avisos(p.id::text, '{validade_proxima}');
    end if;
  end if;
end $$;

create or replace function public.trg_avisos_produto()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  if avisos_ligados() then
    perform avaliar_estoque_produto(new);
    perform avaliar_validade_produto(new);
  end if;
  return null;
end $$;

create trigger trg_produtos_avisos
  after update of estoque_atual, estoque_minimo, validade, ativo on public.produtos
  for each row execute function public.trg_avisos_produto();

-- Varredura completa (validade muda com o passar dos dias). Idempotente.
create or replace function public.verificar_avisos()
returns integer language plpgsql security definer set search_path = public as $$
declare
  p produtos;
  v_antes bigint := (select count(*) from avisos);
begin
  if not is_operador() and auth.uid() is not null then
    raise exception 'Não autorizado' using errcode = '42501';
  end if;
  for p in select * from produtos loop
    perform avaliar_estoque_produto(p);
    perform avaliar_validade_produto(p);
  end loop;
  return (select count(*) from avisos) - v_antes;
end $$;

-- ---------------------------------------------------------------------
-- Avaliações: nota ruim e sugestão de produto
-- ---------------------------------------------------------------------
create or replace function public.trg_avisos_avaliacao()
returns trigger language plpgsql security definer set search_path = public as $$
declare
  v_quem text;
begin
  if not avisos_ligados() then return null; end if;
  select coalesce(m.nome, case new.tipo_cliente when 'visitante' then 'Visitante' else 'Morador' end) into v_quem
    from (select 1) x left join moradores m on m.id = new.morador_id;

  if new.nota <= 2 then
    perform abrir_aviso('avaliacao_baixa', 'atencao', 'Avaliação ' || new.nota || ' de 5 estrelas',
      v_quem || ' deu nota ' || new.nota || coalesce(': “' || new.comentario || '”', ' (sem observação).'),
      '/admin/avaliacoes', new.id::text, true);
  elsif tg_op = 'UPDATE' and old.nota <= 2 then
    perform resolver_avisos(new.id::text, '{avaliacao_baixa}');
  end if;

  if new.sugestao is not null and (tg_op = 'INSERT' or old.sugestao is distinct from new.sugestao) then
    perform abrir_aviso('sugestao_produto', 'info', 'Sugestão de produto: ' || new.sugestao,
      v_quem || ' gostaria de encontrar “' || new.sugestao || '” no mercado.', '/admin/avaliacoes', new.id::text, true);
  end if;
  return null;
end $$;

create trigger trg_avaliacoes_avisos
  after insert or update of nota, comentario, sugestao on public.avaliacoes
  for each row execute function public.trg_avisos_avaliacao();

-- ---------------------------------------------------------------------
-- RLS e realtime
-- ---------------------------------------------------------------------
alter table public.avisos enable row level security;
alter table public.config_avisos enable row level security;
create policy avisos_admin_ler on public.avisos for select to authenticated using (public.is_admin());
create policy avisos_admin_editar on public.avisos for update to authenticated using (public.is_admin()) with check (public.is_admin());
create policy config_avisos_admin on public.config_avisos for all to authenticated using (public.is_admin()) with check (public.is_admin());

revoke all on function public.abrir_aviso(tipo_aviso, gravidade_aviso, text, text, text, text, boolean) from public, anon, authenticated;
revoke all on function public.resolver_avisos(text, tipo_aviso[]) from public, anon, authenticated;

do $$
begin
  if exists (select 1 from pg_publication where pubname = 'supabase_realtime') then
    alter publication supabase_realtime add table public.avisos;
  end if;
  -- verificação diária de validade às 6h (Brasília = 9h UTC), se o pg_cron estiver ativo
  if exists (select 1 from pg_extension where extname = 'pg_cron') then
    perform cron.schedule('verificar-avisos', '0 9 * * *', 'select public.verificar_avisos()');
  end if;
end $$;
